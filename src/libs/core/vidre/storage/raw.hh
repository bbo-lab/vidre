/**@defgroup api-core-storage-raw Raw data file
 * @ingroup api-core-storage
 * @fileinfo
 * @details
 *
 * The raw file format uses [Type-Length-Value](https://en.wikipedia.org/wiki/Type%E2%80%93length%E2%80%93value)
 * (TLV) encoding, inspired by the design principles of ASN.1 (note also some
 * discomfort with other existing file formats such as BigTIFF).
 *
 * The primary goals are:
 *
 *   - Minimal computational overhead during recording
 *   - Self-describing structure (cf. BER encoding, [X.690](https://en.wikipedia.org/wiki/X.690))
 *   - Storage size is intentionally traded off for speed
 *
 * The raw file format is designed to be flexible and extensible, allowing for
 * the inclusion of various types of data streams (e.g., video, audio, metadata)
 * while maintaining a consistent structure. The use of TLV encoding facilitates the
 * addition of new data types and structures without breaking compatibility.
 *
 * Yet, the raw file format is not intended to be a general-purpose container
 * format. It is specifically tailored for the needs of VidRe and may not be
 * suitable for all use cases. For example, it may not be the best choice for
 * long-term archival storage or for sharing data with external parties.
 *
 * Therefore, VidRe also provides tools for converting raw files to more widely
 * used formats (e.g., FFV1, MP4, AVI) for archival and sharing purposes. These tools
 * are designed to preserve the integrity of the original data while providing
 * compatibility with a broader range of software and platforms.
 *
 * **File layout**
 *
 * Each "raw" file consists of:
 *
 *   1. File header   - begins with a magic number and version
 *   2. Data chunks   - the recorded payload (consisting of a chunk header and the actual data)
 *   3. Tail          - finalization metadata
 *
 * During the hot path (active recording), tail information is written to a
 * separate file. The data file is only finalized when recording stops.
 *
 * <i>Header</i>
 *
 * The header must contain sufficient information to identify and interpret the
 * data stream in its entirety. This includes a magic number, version information,
 * and possibly global metadata (e.g., recording settings, device information,
 * possibly operator information, etc.).
 *
 * The contents are 8-byte aligned, tailored towards 64-bit architectures, were
 * unaligned data access can lead to significant performance degradation.
 *
 * In detail, the header consists of:
 * @code{.unparsed}
 * <magic>              // 8 bytes
 * <version>            // 8 bytes (4 bytes major, 4 bytes minor)
 * <plain group         // 16+n bytes
 *    <metadata>*       // m*(16+n) bytes
 * >
 * @endcode
 *
 * <i>Data chunks</i>
 *
 * Every chunk must contain, at minimum:
 *
 *   - Sequence index
 *   - Device timestamp   (generated by the capturing device)
 *   - Host timestamp     (when the data was received)
 *   - Data payload
 *
 * possibly followed by additional metadata (for example a checksum).
 *
 * If possible, that data should feature a fixed stride (e.g., for video frames,
 * the frame size) to allow for efficient reading and seeking.
 *
 * In detail, the chunk header consists of:
 * @code{.unparsed}
 * <chunk                 // 16 bytes
 *     <sequence index>   // 16+8 bytes
 *     <device timestamp> // 16+16 bytes
 *     <host timestamp>   // 16+16 bytes
 *     <payload>          // 16+8+n bytes
 *     [<plain group
 *         <metadata>*
 *     >]
 * >
 * @endcode
 *
 * <i>Tail</i>
 *
 * The tail contains additional metadata that is not needed during live
 * recording. For a camera stream, this includes a sparse mapping of
 * indices to file offsets (for efficient seeking), possibly also
 * error information, in case a recording was unintentionally stopped.
 *
 * Note, as the tail is written to a separate file during recording, it's
 * layout is identical to the header, meaning it also starts with a magic number
 * and version information, followed by TLV-encoded metadata. In contrast to the
 * header, though, the tail, as it rather represents a log of the recording session,
 * does not require grouping.
 *
 * The tail is finalized when recording stops, and the information is merged into
 * the data file with it's length stored in the last 8 bytes of the file. This
 * allows for efficient seeking and retrieval of the tail information.
 *
 * In detail, the header consists of:
 * @code{.unparsed}
 * <magic>              // 8 bytes
 * <version>            // 8 bytes (4 bytes major, 4 bytes minor)
 * <metadata>*          // m*(16+k) bytes
 * [<tail-size>]        // 8 bytes (only in data file, not in tail file)
 * @endcode
 *
 * */

