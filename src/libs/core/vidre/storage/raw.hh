/**@defgroup api-core-storage-raw Raw data file
 * @ingroup api-core-storage
 * @fileinfo
 * @details
 *
 * The raw file format uses Type-Length-Value (TLV) encoding
 * (https://en.wikipedia.org/wiki/Type%E2%80%93length%E2%80%93value), inspired by
 * the design principles of ASN.1 (note also some discomfort with existing file
 * formats such as BigTIFF). The primary goals are:
 *
 *   - Minimal computational overhead during recording
 *   - Self-describing structure (cf. BER encoding, X.690)
 *   - Storage size is intentionally traded off for speed
 *
 * @todo For archiving purposes, VidRe provides tools...
 *
 * **Stream layout**
 *
 * Each data stream (called a "chunk") consists of:
 *
 *   1. File header   - begins with a magic number
 *   2. Data chunks   - the recorded payload
 *   3. Tail          - finalization metadata
 *
 * During the hot path (active recording), tail information is written to a
 * separate file. This file is only finalized when recording stops.
 *
 * <i>Header</i>
 *
 * The header must contain sufficient information to identify and interpret the
 * data stream. For a camera stream, this includes camera type and configuration.
 *
 * <i>Data chunks</i>
 *
 * Every chunk must contain, at minimum:
 *
 *   - Sequence index
 *   - Device timestamp   (generated by the capturing device)
 *   - Host timestamp     (when the data was received)
 *
 * <i>Tail</i>
 *
 * The tail contains additional metadata that is not needed during live
 * recording. For a camera stream, this includes a sparse mapping of
 * indices to file offsets (for efficient seeking), possibly also
 * error information, in case a recording was unintentionally stopped.
 * 
 * @todo a detailed description of the file format (see "major"/"minor" below) is required
 *
 * */

